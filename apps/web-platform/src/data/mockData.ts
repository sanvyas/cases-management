export function getUsageData(tenantId: string): UsageMetric[] {
  const base = tenantId === 'env-varanasi-nnn' ? 1600 : tenantId === 'env-gorakhpur-nnn' ? 1050 : 400;
  const days: UsageMetric[] = [];
  for (let i = 29; i >= 0; i--) {
    const d = new Date();
    d.setDate(d.getDate() - i);
    const jitter = 0.7 + Math.random() * 0.6;
    const weekday = d.getDay() > 0 && d.getDay() < 6;
    const mult = weekday ? jitter : jitter * 0.4;
    days.push({
      date: d.toISOString().slice(0, 10),
      cases: Math.round(base * mult),
      voiceSessions: Math.round(base * 0.15 * mult),
      whatsappMessages: Math.round(base * 2.5 * mult),
      smsCount: Math.round(base * 1.8 * mult),
      apiCalls: Math.round(base * 12 * mult),
      storageGB: +(50 + i * 0.3).toFixed(1),
    });
  }
  return days;
}

